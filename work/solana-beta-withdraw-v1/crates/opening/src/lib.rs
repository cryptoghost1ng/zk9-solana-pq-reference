//! PCS claimed-opening absorption only, NOT Merkle/FRI or payment verification.
#![no_std]
#![forbid(unsafe_code)]
pub mod sponge;
use prefix::challenger::Challenger;
use zk9_proof_staged::Reader;
pub const SEED:&[u8]=include_bytes!("../../../generated/pcs-seed.bin");
pub const VALUES_BYTES:usize=(2*(prefix::WIDTH+8)+17*16)*32;
pub const CHECKPOINT_BYTES:usize=352;
pub const MAX_STEP:usize=6144;
#[derive(Debug,Clone,Copy,PartialEq,Eq)]pub enum Error{Format,Shape,State,Encoding,Limit,Complete}
pub struct Claims<'a>{slices:[&'a[u8];38]}
struct Cursor<'a>{bytes:&'a[u8],pos:usize}
impl<'a> Cursor<'a>{
 fn take(&mut self,n:usize)->Result<&'a[u8],Error>{let end=self.pos.checked_add(n).ok_or(Error::Encoding)?;let v=self.bytes.get(self.pos..end).ok_or(Error::Encoding)?;self.pos=end;Ok(v)}
 fn count(&mut self,want:u8)->Result<(),Error>{if self.take(1)?!=[want]{return Err(Error::Shape)}Ok(())}
}
impl<'a> Claims<'a>{
 /// The caller must authenticate the completed format checkpoint AND source.
 pub fn from_trusted_format(wire:&'a[u8],format:&[u8])->Result<Self,Error>{
  let v=prefix::views_from_trusted_format(wire,format).map_err(|_|Error::Shape)?;
  let proof=wire.get(3945..).ok_or(Error::Format)?;
  let r=Reader::resume_trusted(proof,format).map_err(|_|Error::Format)?;if !r.done(){return Err(Error::Format)}
  let s=r.sections()[2];let mut c=Cursor{bytes:proof.get(s.start as usize..s.end as usize).ok_or(Error::Format)?,pos:0};
  c.count(3)?;let mut slices=[&[][..];38];let mut i=0;
  for round in 0..3{
   let matrices=if round==2{16}else{1};c.count(matrices)?;
   for matrix in 0..matrices{let points=if round==1{2}else{1};c.count(points)?;
    for point in 0..points{
     slices[i]=match round{0=>v.random.bytes(),1=>if point==0{v.trace.bytes()}else{v.next.bytes()},_=>v.quotient[matrix as usize].bytes()};i+=1;
     c.count(8)?;slices[i]=c.take(256)?;i+=1;
    }
   }
  }
  // Batch PoW is disabled in the trusted profile, so its unused slot MUST be zero.
  if c.take(4)?!=[0;4]||i!=38||slices.iter().map(|s|s.len()).sum::<usize>()!=VALUES_BYTES{return Err(Error::Shape)}
  Ok(Self{slices})
 }
 pub fn total_bytes(&self)->usize{SEED.len()+VALUES_BYTES}
 fn slice_at(&self,mut at:usize)->Option<&[u8]>{
  for s in core::iter::once(SEED).chain(self.slices.iter().copied()){if at<s.len(){return Some(&s[at..])}at-=s.len();}None
 }
}
pub struct Progress{hash:sponge::Absorber,absorbed:usize,done:bool,alpha:[u32;8],challenger:[u8;80]}
impl Progress{
 /// Prefix result must be authenticated, generated by this verifier on this source.
 pub fn start(trusted_prefix:&[u8])->Result<Self,Error>{
  if trusted_prefix.len()!=prefix::RESULT_BYTES||&trusted_prefix[..8]!=b"ZK9PFXW2"{return Err(Error::State)}
  let saved=&trusted_prefix[72..152];Challenger::resume_trusted(saved).map_err(|_|Error::State)?;
  // Observing PCS's nonempty seed discards the remaining output bytes. The
  // chained digest stays in the hash input, exactly as in HashChallenger.
  let mut hash=sponge::Absorber::new();hash.update(&saved[16..80]);
  Ok(Self{hash,absorbed:0,done:false,alpha:[0;8],challenger:[0;80]})
 }
 pub fn absorbed(&self)->usize{self.absorbed}pub fn done(&self)->bool{self.done}
 pub fn result(&self)->Option<([u32;8],[u8;80])>{self.done.then_some((self.alpha,self.challenger))}
 pub fn advance(&mut self,claims:&Claims,limit:usize)->Result<bool,Error>{
  if self.done{return Err(Error::Complete)}if limit==0||limit>MAX_STEP{return Err(Error::Limit)}
  let end=(self.absorbed+limit).min(claims.total_bytes());
  while self.absorbed<end{let s=claims.slice_at(self.absorbed).ok_or(Error::State)?;let n=s.len().min(end-self.absorbed);self.hash.update(&s[..n]);self.absorbed+=n;}
  if self.absorbed==claims.total_bytes(){
   let digest=self.hash.clone().finish();let mut snap=[0;80];snap[..8].copy_from_slice(b"ZK9HS01\0");snap[8]=64;snap[16..].copy_from_slice(&digest);
   let mut c=Challenger::resume_trusted(&snap).map_err(|_|Error::State)?;self.alpha=c.sample_extension();self.challenger=c.checkpoint_after_sample().map_err(|_|Error::State)?;self.done=true;
  }Ok(self.done)
 }
 pub fn checkpoint(&self,out:&mut[u8])->Result<(),Error>{
  if out.len()!=CHECKPOINT_BYTES{return Err(Error::State)}out.fill(0);out[..8].copy_from_slice(b"ZK9PCS01");out[8..12].copy_from_slice(&(self.absorbed as u32).to_le_bytes());out[12]=u8::from(self.done);
  self.hash.checkpoint(&mut out[16..232])?;
  for (b,x) in out[232..264].chunks_exact_mut(4).zip(self.alpha){b.copy_from_slice(&x.to_le_bytes());}out[264..344].copy_from_slice(&self.challenger);Ok(())
 }
 pub fn resume_trusted(saved:&[u8])->Result<Self,Error>{
  if saved.len()!=CHECKPOINT_BYTES||&saved[..8]!=b"ZK9PCS01"||saved[12]>1||saved[13..16].iter().any(|x|*x!=0)||saved[344..].iter().any(|x|*x!=0){return Err(Error::State)}
  let absorbed=u32::from_le_bytes(saved[8..12].try_into().unwrap())as usize;let done=saved[12]==1;
  if absorbed>SEED.len()+VALUES_BYTES||done!=(absorbed==SEED.len()+VALUES_BYTES){return Err(Error::State)}
  let hash=sponge::Absorber::resume_trusted(&saved[16..232])?;
  if saved[24]as usize!=(64+absorbed)%72{return Err(Error::State)}
  let mut alpha=[0;8];for(x,b)in alpha.iter_mut().zip(saved[232..264].chunks_exact(4)){*x=u32::from_le_bytes(b.try_into().unwrap());if *x>=prefix::PRIME{return Err(Error::State)}}
  let challenger:[u8;80]=saved[264..344].try_into().unwrap();
  if done{Challenger::resume_trusted(&challenger).map_err(|_|Error::State)?;}else if saved[232..344].iter().any(|x|*x!=0){return Err(Error::State)}
  Ok(Self{hash,absorbed,done,alpha,challenger})
 }
}
