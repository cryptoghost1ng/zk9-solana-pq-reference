"""Generates managed-validator-ledger.mjs from solana-unified-wallet-v1/managed-validator.mjs (frozen, untouched) by exact-match patches (each asserted to match exactly once).
The ONLY behavioural difference: the local validator keeps its whole ledger (--limit-ledger-size 1000000000 instead of 10000), so that a run can read back every transaction at the end.
full-08 showed why: with 10000 shreds the validator had forgotten 11,484 of the 11,726 transactions the sponsor had paid for. The second change only keeps the relative import of host-lease.mjs working from this directory.
usage: make_validator_ledger.py (once; refuses to overwrite)"""
import difflib
from pathlib import Path
HERE=Path(__file__).resolve().parent;WORK=HERE.parent
SRC=WORK/'solana-unified-wallet-v1/managed-validator.mjs';OUT=HERE/'managed-validator-ledger.mjs'
assert not OUT.exists(),'refusing to overwrite managed-validator-ledger.mjs'
text=SRC.read_text()
PAIRS=[
 ("// Full connected-wallet qualification bootstrap. New run only; never changes a live publication run.\n",
  "// LEDGER-RETENTION variant of ../solana-unified-wallet-v1/managed-validator.mjs (frozen, untouched), generated by make_validator_ledger.py: the validator keeps its whole ledger.\n// Full connected-wallet qualification bootstrap. New run only; never changes a live publication run.\n"),
 ("import {hostLease} from './host-lease.mjs';","import {hostLease} from '../solana-unified-wallet-v1/host-lease.mjs';"),
 ("'--limit-ledger-size','10000'","'--limit-ledger-size','1000000000'"),
]
new=text
for old,rep in PAIRS:
    assert new.count(old)==1,(old[:80],new.count(old))
    new=new.replace(old,rep)
OUT.write_text(new)
(HERE/'managed-validator-ledger.mjs.diff').write_text(''.join(difflib.unified_diff(text.splitlines(True),new.splitlines(True),'solana-unified-wallet-v1/managed-validator.mjs','solana-onion-e2e-v1/managed-validator-ledger.mjs')))
print('written',OUT.name,len(new),'bytes')
